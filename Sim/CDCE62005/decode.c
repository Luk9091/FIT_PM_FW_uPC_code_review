#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
// Struktura ramki dla CDCE zaczyna od najmniej znaczącego bajtu, i ma szerokość czterech bajtów


void print_words(uint32_t *words, size_t size){
	for (size_t i = 0; i < size; i++){
		printf("%03lu: 0x%08X\n", i, words[i]);
	}
}

int main(){
	uint8_t raw_bytes[] = {0x08, 0x18, 0x00, 0x00, 0x20, 0x03, 0x07, 0xeb, 0x21, 0x03, 0x80, 0xeb, 0x02, 0x03, 0x06, 0xeb, 0x03, 0x03, 0x80, 0xeb, 0x34, 0x03, 0x84, 0x68, 0x35, 0x0f, 0x04, 0x40, 0x86, 0x01, 0xfe, 0xc0, 0xf7, 0xbb, 0x42, 0xbd, 0x86, 0x01, 0xfe, 0xc4, 0x20, 0x03, 0x07, 0x69, 0x21, 0x03, 0x80, 0x69, 0x02, 0x03, 0x06, 0x69, 0x03, 0x03, 0x80, 0x69, 0x34, 0x03, 0x84, 0x68, 0x35, 0x0f, 0x04, 0x40, 0x86, 0x01, 0xee, 0xc0, 0xf7, 0x37, 0x78, 0xbc, 0x1f, 0x00};

	uint32_t words[128] = {0};


	size_t bytes_index = 0;
	size_t words_index = 0;
	for (bytes_index = 0; bytes_index < sizeof(raw_bytes); bytes_index++){
		words[words_index] |= raw_bytes[bytes_index] << (8 * (bytes_index % 4));
		if (bytes_index % 4 == 3){
			words_index++;
		}
	}


	print_words(words, words_index + 1);
	return 0;
}
